# Redeploys the Azure Container Instances Kafka broker (readingpal-kafka) with
# aci-start-with-topics.sh as its startup command, so the topics are recreated every time
# the broker starts. Everything else (image, environment variables, size, DNS name, ports,
# Log Analytics logging) is read from the live container group and kept exactly as it is.
#
# Usage (from the repo root, signed in with `az login`):
#   powershell -ExecutionPolicy Bypass -File infrastructure/kafka/deploy-aci-kafka.ps1
#   powershell -ExecutionPolicy Bypass -File infrastructure/kafka/deploy-aci-kafka.ps1 -Restore   # back to the image's default startup
#
# Redeploying restarts the broker, which wipes its topics and messages (it has no persistent
# storage). Lending keeps unsent events in its outbox and resends them; Inventory events sent
# during the restart window are lost. Expect about a minute of broker downtime.
param(
    [string]$ResourceGroup = "reading-pal-v3",
    [string]$Name = "readingpal-kafka",
    [string]$Subscription = "65bc8484-12cb-42f4-a420-42d31f7d261f",
    [switch]$Restore,
    # Writes the definition that would be deployed (logging key redacted) and changes nothing.
    [string]$DryRun
)
$ErrorActionPreference = "Stop"

$az = (Get-Command az -ErrorAction SilentlyContinue).Source
if (-not $az) { $az = "C:\Program Files\Microsoft SDKs\Azure\CLI2\wbin\az.cmd" }
$common = @("--resource-group", $ResourceGroup, "--subscription", $Subscription)

$live = & $az container show @common --name $Name -o json | ConvertFrom-Json
if (-not $live) { throw "Container group '$Name' not found in '$ResourceGroup'." }
$container = $live.containers[0]

$stamp = Get-Date -Format "yyyyMMdd-HHmmss"
if (-not $DryRun) {
    $backup = Join-Path $env:TEMP "$Name-backup-$stamp.yaml"
    & $az container export @common --name $Name --file $backup | Out-Null
    Write-Host "Backed up the current definition to $backup"
}

$spec = [ordered]@{
    apiVersion = "2023-05-01"
    location   = $live.location
    name       = $Name
    type       = "Microsoft.ContainerInstance/containerGroups"
    properties = [ordered]@{
        osType        = $live.osType
        sku           = $live.sku
        restartPolicy = $live.restartPolicy
        containers    = @([ordered]@{
            name       = $container.name
            properties = [ordered]@{
                image                = $container.image
                environmentVariables = @($container.environmentVariables | ForEach-Object { [ordered]@{ name = $_.name; value = $_.value } })
                ports                = @($container.ports | ForEach-Object { [ordered]@{ port = $_.port; protocol = $_.protocol } })
                resources            = [ordered]@{ requests = [ordered]@{ cpu = $container.resources.requests.cpu; memoryInGB = $container.resources.requests.memoryInGb } }
            }
        })
        ipAddress     = [ordered]@{
            type                              = $live.ipAddress.type
            dnsNameLabel                      = $live.ipAddress.dnsNameLabel
            autoGeneratedDomainNameLabelScope = $live.ipAddress.autoGeneratedDomainNameLabelScope
            ports                             = @($live.ipAddress.ports | ForEach-Object { [ordered]@{ port = $_.port; protocol = $_.protocol } })
        }
    }
}

if (-not $Restore) {
    $startup = (Get-Content -Raw (Join-Path $PSScriptRoot "aci-start-with-topics.sh")) -replace "`r`n", "`n"
    $spec.properties.containers[0].properties.command = @("/bin/bash", "-c", $startup)
}

# The workspace key is never returned by `container show`/`export`, so look it up to keep logging on.
$workspaceId = $live.diagnostics.logAnalytics.workspaceId
if ($DryRun) {
    if ($workspaceId) { $spec.properties.diagnostics = [ordered]@{ logAnalytics = [ordered]@{ workspaceId = $workspaceId; workspaceKey = "<looked up at deploy time>"; logType = $live.diagnostics.logAnalytics.logType } } }
    [IO.File]::WriteAllText($DryRun, ($spec | ConvertTo-Json -Depth 20))
    Write-Host "Dry run: wrote the definition to $DryRun. Nothing was changed."
    return
}
if ($workspaceId) {
    $workspace = & $az monitor log-analytics workspace list --subscription $Subscription --query "[?customerId=='$workspaceId'] | [0]" -o json | ConvertFrom-Json
    $key = & $az monitor log-analytics workspace get-shared-keys --subscription $Subscription --resource-group $workspace.resourceGroup --workspace-name $workspace.name --query primarySharedKey -o tsv
    $spec.properties.diagnostics = [ordered]@{ logAnalytics = [ordered]@{ workspaceId = $workspaceId; workspaceKey = $key; logType = $live.diagnostics.logAnalytics.logType } }
}

# JSON is valid YAML, which is what `az container create --file` reads.
$tmp = Join-Path $env:TEMP "$Name-deploy-$stamp.json"
try {
    [IO.File]::WriteAllText($tmp, ($spec | ConvertTo-Json -Depth 20))
    Write-Host "Redeploying $Name$(if ($Restore) { ' with the default startup command' } else { ' with topic creation on startup' })..."
    & $az container create @common --file $tmp -o none
    if ($LASTEXITCODE -ne 0) { throw "az container create failed; the backup is at $backup" }
}
finally { Remove-Item $tmp -ErrorAction SilentlyContinue }

if (-not $Restore) {
    Write-Host "Waiting for the broker to create its topics..."
    for ($i = 1; $i -le 36; $i++) {
        $logs = & $az container logs @common --name $Name 2>$null | Out-String
        if ($logs -match "topic-init: done - (\d+) application topics present") { Write-Host "Broker is up: $($Matches[1]) application topics present."; return }
        if ($logs -match "topic-init: Kafka exited") { throw "Kafka exited during startup; check 'az container logs'. Backup: $backup" }
        Start-Sleep -Seconds 10
    }
    Write-Warning "No 'topic-init: done' line after 6 minutes; check 'az container logs' manually."
}
